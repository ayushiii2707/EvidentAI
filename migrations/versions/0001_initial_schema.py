def _create_integrity_triggers() -> None:
    pairs = ", ".join(f"('{a}', '{b}')" for a, b in ALLOWED_TRANSITIONS)
    op.execute(f"""
    CREATE FUNCTION evidentai_version_insert() RETURNS trigger LANGUAGE plpgsql AS $$
    BEGIN
      IF NEW.status <> 'pending' THEN
        RAISE EXCEPTION 'document versions must be created as pending, got %', NEW.status
          USING ERRCODE = 'check_violation';
      END IF;
      RETURN NEW;
    END $$;

    CREATE FUNCTION evidentai_version_update() RETURNS trigger LANGUAGE plpgsql AS $$
    BEGIN
      IF (NEW.workspace_id, NEW.product_id, NEW.document_id, NEW.release_id, NEW.source_sha256)
         IS DISTINCT FROM
         (OLD.workspace_id, OLD.product_id, OLD.document_id, OLD.release_id, OLD.source_sha256)
      THEN
        RAISE EXCEPTION 'document version identity columns are immutable'
          USING ERRCODE = 'check_violation';
      END IF;
      IF NEW.status = OLD.status THEN
        RETURN NEW;
      END IF;
      IF (OLD.status, NEW.status) NOT IN ({pairs}) THEN
        RAISE EXCEPTION 'illegal document version transition % -> %', OLD.status, NEW.status
          USING ERRCODE = 'check_violation';
      END IF;
      IF NEW.status = 'purged' THEN
        IF EXISTS (
          SELECT 1 FROM scope_snapshot_versions sv
          JOIN scope_snapshots s ON s.id = sv.snapshot_id
          WHERE sv.document_version_id = NEW.id AND s.state = 'open'
        ) THEN
          RAISE EXCEPTION 'version % is pinned by an open scope snapshot', NEW.id
            USING ERRCODE = 'object_in_use';
        END IF;
        -- Purged means no content remains; chunks cascade from sections.
        DELETE FROM sections WHERE document_version_id = NEW.id;
      END IF;
      NEW.status_changed_at := now();
      RETURN NEW;
    END $$;

    CREATE TRIGGER trg_versions_insert BEFORE INSERT ON document_versions
      FOR EACH ROW EXECUTE FUNCTION evidentai_version_insert();
    CREATE TRIGGER trg_versions_update BEFORE UPDATE ON document_versions
      FOR EACH ROW EXECUTE FUNCTION evidentai_version_update();

    -- Content may only be written while a version is being indexed.
    CREATE FUNCTION evidentai_content_write() RETURNS trigger LANGUAGE plpgsql AS $$
    DECLARE v_status text;
    BEGIN
      SELECT status INTO v_status FROM document_versions WHERE id = NEW.document_version_id;
      IF v_status IS DISTINCT FROM 'indexing' THEN
        RAISE EXCEPTION 'cannot write % for a version in status %', TG_TABLE_NAME, v_status
          USING ERRCODE = 'check_violation';
      END IF;
      RETURN NEW;
    END $$;
    CREATE TRIGGER trg_sections_write BEFORE INSERT OR UPDATE ON sections
      FOR EACH ROW EXECUTE FUNCTION evidentai_content_write();
    CREATE TRIGGER trg_chunks_write BEFORE INSERT OR UPDATE ON chunks
      FOR EACH ROW EXECUTE FUNCTION evidentai_content_write();

    -- A snapshot pins only versions that are active at the moment it is created,
    -- for releases of its own product.
    CREATE FUNCTION evidentai_snapshot_version_insert() RETURNS trigger LANGUAGE plpgsql AS $$
    DECLARE v record; s record;
    BEGIN
      SELECT status, release_id, product_id INTO v
        FROM document_versions WHERE id = NEW.document_version_id;
      SELECT product_id, release_ids, state INTO s FROM scope_snapshots WHERE id = NEW.snapshot_id;
      IF s.state <> 'open' THEN
        RAISE EXCEPTION 'cannot add versions to a closed snapshot'
          USING ERRCODE = 'check_violation';
      END IF;
      IF v.status <> 'active' THEN
        RAISE EXCEPTION 'only active versions can be pinned, got %', v.status
          USING ERRCODE = 'check_violation';
      END IF;
      IF v.product_id <> s.product_id OR NOT (v.release_id = ANY (s.release_ids)) THEN
        RAISE EXCEPTION 'version is outside the snapshot product/release scope'
          USING ERRCODE = 'check_violation';
      END IF;
      RETURN NEW;
    END $$;
    CREATE TRIGGER trg_snapshot_versions_insert BEFORE INSERT ON scope_snapshot_versions
      FOR EACH ROW EXECUTE FUNCTION evidentai_snapshot_version_insert();

    CREATE FUNCTION evidentai_snapshot_write() RETURNS trigger LANGUAGE plpgsql AS $$
    BEGIN
      IF TG_OP = 'INSERT' AND EXISTS (
        SELECT 1 FROM unnest(NEW.release_ids) r
        WHERE NOT EXISTS (SELECT 1 FROM releases WHERE id = r AND product_id = NEW.product_id)
      ) THEN
        RAISE EXCEPTION 'snapshot releases must belong to its product'
          USING ERRCODE = 'foreign_key_violation';
      END IF;
      IF TG_OP = 'UPDATE' THEN
        IF (NEW.workspace_id, NEW.product_id, NEW.release_ids)
           IS DISTINCT FROM (OLD.workspace_id, OLD.product_id, OLD.release_ids) THEN
          RAISE EXCEPTION 'snapshot scope is immutable' USING ERRCODE = 'check_violation';
        END IF;
        IF OLD.state = 'closed' AND NEW.state <> 'closed' THEN
          RAISE EXCEPTION 'closed snapshots cannot be reopened' USING ERRCODE = 'check_violation';
        END IF;
      END IF;
      RETURN NEW;
    END $$;
    CREATE TRIGGER trg_snapshots_write BEFORE INSERT OR UPDATE ON scope_snapshots
      FOR EACH ROW EXECUTE FUNCTION evidentai_snapshot_write();

    CREATE FUNCTION evidentai_embedding_dims() RETURNS trigger LANGUAGE plpgsql AS $$
    DECLARE expected int;
    BEGIN
      SELECT dimensions INTO expected FROM embedding_models WHERE id = NEW.model_id;
      IF vector_dims(NEW.embedding) <> expected THEN
        RAISE EXCEPTION 'embedding has % dimensions, model % expects %',
          vector_dims(NEW.embedding), NEW.model_id, expected USING ERRCODE = 'check_violation';
      END IF;
      RETURN NEW;
    END $$;
    CREATE TRIGGER trg_embeddings_dims BEFORE INSERT OR UPDATE ON embeddings
      FOR EACH ROW EXECUTE FUNCTION evidentai_embedding_dims();
    """)


def _create_row_level_security() -> None:
    # NULL when unset or reset to '' at the end of a transaction: comparisons with NULL
    # are never true, so a session that forgot to set a workspace sees no rows.
    op.execute("""
    CREATE FUNCTION evidentai_current_workspace() RETURNS uuid LANGUAGE sql STABLE AS $$
      SELECT NULLIF(current_setting('app.workspace_id', true), '')::uuid
    $$;
    ALTER TABLE workspaces ENABLE ROW LEVEL SECURITY;
    CREATE POLICY tenant_isolation ON workspaces
      USING (id = evidentai_current_workspace())
      WITH CHECK (id = evidentai_current_workspace());
    """)
    for table in TENANT_TABLES:
        op.execute(f"""
        ALTER TABLE {table} ENABLE ROW LEVEL SECURITY;
        CREATE POLICY tenant_isolation ON {table}
          USING (workspace_id = evidentai_current_workspace())
          WITH CHECK (workspace_id = evidentai_current_workspace());
        """)



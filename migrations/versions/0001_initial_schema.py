    # not granted: no CP2/CP3 code path needs it, and reading it would expose every
    # tenant's user emails. Grants are revisited when authentication lands (CP7).
    tables = ", ".join(("workspaces",) + TENANT_TABLES)
    op.execute(f"""
    DO $$ BEGIN
      IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'evidentai_app') THEN
        GRANT USAGE ON SCHEMA public TO evidentai_app;
        GRANT SELECT, INSERT, UPDATE, DELETE ON {tables} TO evidentai_app;
        GRANT SELECT ON embedding_models TO evidentai_app;
      END IF;
    END $$;
    """)


